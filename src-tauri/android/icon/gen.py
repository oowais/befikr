#!/usr/bin/env python3
"""Generate the Befikr app icon ("breeze checklist") as Android resources + SVGs.

Run from anywhere: python3 src-tauri/android/icon/gen.py
Writes src-tauri/android/res/ (copied into the generated Android project by CI)
and src-tauri/android/icon/icon-{light,dark}.svg (source for PNG icons).
Light = sage paper, dark = charcoal + mint (values-night; launchers that honour
night resources switch, others show light).
"""
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE.parent / "res"

PALETTES = {
    "light": dict(bg="#E3ECDC", top="#7A9A76", mid="#24452A", low="#7A9A76", open="#E07A5F"),
    "dark": dict(bg="#23262B", top="#B9F6CA", mid="#FFFFFF", low="#69F0AE", open="#69F0AE"),
}

def wave(x0, x1, y, amp, n=24):
    pts = [(x0 + (x1 - x0) * i / n, y + amp * math.sin(2 * math.pi * i / n)) for i in range(n + 1)]
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts)

def tick(x, y):
    return f"M{x},{y} l3.6,3.6 l7.2,-8"

# (path data, colour role, stroke width) in a 108x108 adaptive-icon canvas.
STROKES = [
    (tick(26, 38), "top", 4.6), (wave(43, 80, 38, 3.4), "top", 6.0),
    (tick(26, 54), "mid", 4.6), (wave(43, 86, 54, 3.8), "mid", 6.5),
    (wave(43, 76, 70, 3.4), "low", 6.0),
]
OPEN = (31.5, 70, 4.8, 3.6)  # open-item ring: cx, cy, r, stroke
SCALE = 0.95  # keep everything inside the 66dp safe circle
# Notification small icon: no safe circle, so the glyph fills ~85% of it.
STAT_SCALE = 1.4

def ring_path(cx, cy, r):
    return f"M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0"

def vector(color_of, alpha_of=lambda role: 1.0, scale=SCALE):
    paths = [
        f'    <path android:pathData="{d}" android:strokeColor="{color_of(role)}" android:strokeAlpha="{alpha_of(role)}"\n'
        f'        android:strokeWidth="{w}" android:strokeLineCap="round" android:strokeLineJoin="round"/>'
        for d, role, w in STROKES
    ]
    cx, cy, r, w = OPEN
    paths.append(
        f'    <path android:pathData="{ring_path(cx, cy, r)}" android:strokeColor="{color_of("open")}"\n'
        f'        android:strokeAlpha="{alpha_of("open")}" android:strokeWidth="{w}"/>'
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by src-tauri/android/icon/gen.py -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
        f'  <group android:scaleX="{scale}" android:scaleY="{scale}" android:pivotX="54" android:pivotY="54">\n'
        + "\n".join(paths) + "\n  </group>\n</vector>\n"
    )

def svg(p, rx=26):
    body = "".join(
        f'<path d="{d}" fill="none" stroke="{p[role]}" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"/>'
        for d, role, w in STROKES
    )
    cx, cy, r, w = OPEN
    body += f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{p["open"]}" stroke-width="{w}"/>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><rect width="108" height="108" rx="{rx}" fill="{p["bg"]}"/>'
            f'<g transform="translate(54 54) scale({SCALE}) translate(-54 -54)">{body}</g></svg>\n')

def write(rel, text):
    path = RES / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)

def main():
    for variant, folder in (("light", "values"), ("dark", "values-night")):
        p = PALETTES[variant]
        write(f"{folder}/ic_launcher_colors.xml",
              '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by src-tauri/android/icon/gen.py -->\n<resources>\n'
              + "".join(f'  <color name="ic_launcher_{k}">{v}</color>\n' for k, v in p.items()) + "</resources>\n")
        (HERE / f"icon-{variant}.svg").write_text(svg(p))
    write("drawable/ic_launcher_fg.xml", vector(lambda role: f"@color/ic_launcher_{role}"))
    # Monochrome (themed icons): system tints it; hierarchy via alpha.
    write("drawable/ic_launcher_mono.xml",
          vector(lambda role: "#FF000000", lambda role: 1.0 if role in ("mid", "open") else 0.6))
    # Notification small icon: white silhouette.
    write("drawable/ic_stat_befikr.xml",
          vector(lambda role: "#FFFFFFFF", lambda role: 1.0 if role in ("mid", "open") else 0.7, STAT_SCALE))
    adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by src-tauri/android/icon/gen.py -->\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '  <background android:drawable="@color/ic_launcher_bg"/>\n'
                '  <foreground android:drawable="@drawable/ic_launcher_fg"/>\n'
                '  <monochrome android:drawable="@drawable/ic_launcher_mono"/>\n</adaptive-icon>\n')
    write("mipmap-anydpi-v26/ic_launcher.xml", adaptive)
    write("mipmap-anydpi-v26/ic_launcher_round.xml", adaptive)

if __name__ == "__main__":
    main()
